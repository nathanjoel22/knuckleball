#!/usr/bin/env node
// P2-05 (Oct 15 2026): renders the app icons and the iOS splash images from ONE source, assets/app-icon.svg, with the
// Chrome already installed on this Mac (headless) -- no npm package, no outside service, no build step for the site.
// Run by hand after changing the icon:   node scripts/splash.js
// Writes icons/ (192, 512, 512 maskable, 180 Apple, 32 favicon) and splash/ (every iPhone / iPad size, both
// orientations), and prints the <link> tags for the pages that carry them. Output is committed; bump CACHE_VERSION.
const fs = require('fs'), path = require('path'), { execFileSync } = require('child_process');
const ROOT = path.join(__dirname, '..');
const CHROME = process.env.CHROME || '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome';
const SVG = fs.readFileSync(path.join(ROOT, 'assets/app-icon.svg'), 'utf8').replace(/<!--[\s\S]*?-->/, '');
// the font goes in each render page itself, so it's there before Chrome paints (a file link sometimes lost the race)
const FONT = 'data:font/ttf;base64,' + fs.readFileSync(path.join(ROOT, 'vendor/fonts/BlackOpsOne-Regular.ttf')).toString('base64');
const BRAND = '#061A12';
const TMP = fs.mkdtempSync(path.join(require('os').tmpdir(), 'kb-splash-'));

// Apple's current sizes: CSS width x height @ pixel ratio (portrait). plans/p2-05-preconditions.md item 4.
const DEVICES = [
  [440, 956, 3], [420, 912, 3], [402, 874, 3], [430, 932, 3], [393, 852, 3], [428, 926, 3], [390, 844, 3],
  [375, 812, 3], [414, 896, 3], [414, 896, 2], [414, 736, 3], [375, 667, 2],
  [1032, 1376, 2], [1024, 1366, 2], [834, 1210, 2], [834, 1194, 2], [820, 1180, 2], [810, 1080, 2], [744, 1133, 2], [768, 1024, 2]
];

function shoot(html, w, h, out, tries = 3){
  const f = path.join(TMP, 'p.html');
  fs.writeFileSync(f, html);
  try { fs.unlinkSync(out) } catch (e) {}
  try { run(f, w, h, out) } catch (e) { if (tries > 1) return shoot(html, w, h, out, tries - 1); throw e }   // Chrome now and then stalls
  if(!fs.existsSync(out)) { if (tries > 1) return shoot(html, w, h, out, tries - 1); throw new Error('Chrome wrote nothing for ' + out) }
}
function run(f, w, h, out){
  execFileSync(CHROME, ['--headless=new', '--disable-gpu', '--hide-scrollbars', '--force-device-scale-factor=1',
    '--allow-file-access-from-files', `--window-size=${w},${h}`, '--virtual-time-budget=2000', `--screenshot=${out}`, 'file://' + f],
    { stdio: 'ignore', timeout: 60000 });
}
const page = (body, bg) => `<!doctype html><html><head><meta charset="utf-8"><style>
  @font-face{ font-family:'Black Ops One'; src:url('${FONT}') format('truetype'); font-display:block; }
  html,body{ margin:0; width:100%; height:100%; background:${bg}; overflow:hidden; }
  body{ display:flex; flex-direction:column; align-items:center; justify-content:center; }
  svg{ display:block; }</style></head><body>${body}</body></html>`;
const icon = px => SVG.replace(/width="1024" height="1024"/, `width="${px}" height="${px}"`);

fs.mkdirSync(path.join(ROOT, 'icons'), { recursive: true });
fs.mkdirSync(path.join(ROOT, 'splash'), { recursive: true });
// Chrome won't lay out a page narrower than ~500px, so each icon is drawn once at 1024 and scaled down with macOS's
// own sips (built in, nothing to install).
const big = path.join(TMP, 'icon-1024.png'), bigMask = path.join(TMP, 'mask-1024.png');
shoot(page(icon(1024), BRAND), 1024, 1024, big);
// maskable: the same art at 80% on a full-bleed square, so any mask shape keeps it whole
shoot(page(icon(820), BRAND), 1024, 1024, bigMask);
const scale = (src, px, name) => execFileSync('sips', ['-z', String(px), String(px), src, '--out', path.join(ROOT, 'icons', name)], { stdio: 'ignore' });
for (const [name, px] of [['icon-192.png', 192], ['icon-512.png', 512], ['apple-touch-icon.png', 180], ['favicon-32.png', 32]]) scale(big, px, name);
scale(bigMask, 512, 'icon-maskable-512.png');

const links = [];
for (const [w, h, r] of DEVICES) {
  for (const orient of ['portrait', 'landscape']) {
    const pw = (orient === 'portrait' ? w : h) * r, ph = (orient === 'portrait' ? h : w) * r;
    const name = `splash-${pw}x${ph}.png`;
    const ic = Math.round(Math.min(pw, ph) * 0.28);
    shoot(page(icon(ic) + `<div style="margin-top:${Math.round(ic * 0.12)}px;font:${Math.round(ic * 0.2)}px 'Black Ops One';color:#FFFFFF;letter-spacing:0.02em">KNUCKLEBALL</div>`, BRAND),
      pw, ph, path.join(ROOT, 'splash', name));
    links.push(`<link rel="apple-touch-startup-image" href="splash/${name}" media="(device-width: ${w}px) and (device-height: ${h}px) and (-webkit-device-pixel-ratio: ${r}) and (orientation: ${orient})">`);
  }
}
fs.writeFileSync(path.join(ROOT, 'splash', 'links.html'), '<!-- P2-05: generated by scripts/splash.js -- iOS splash images -->\n' + links.join('\n') + '\n');
console.log(`icons: 5 · splash: ${links.length} · links: splash/links.html`);
